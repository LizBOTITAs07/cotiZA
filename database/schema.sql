CREATE TABLE IF NOT EXISTS catalogo_servicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto VARCHAR(100) NOT NULL UNIQUE,
    precio_base NUMERIC(10, 2) NOT NULL CHECK (precio_base >= 0),
    categoria VARCHAR(50) NOT NULL,
    participa_descuento BOOLEAN NOT NULL DEFAULT FALSE,
    stock_maximo INTEGER CHECK (stock_maximo IS NULL OR stock_maximo >= 0)
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    telefono VARCHAR(30),
    email VARCHAR(254),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cotizaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
    fecha_evento DATE NOT NULL,
    estado_reserva VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_reserva IN ('pendiente', 'confirmada', 'cancelada')),
    subtotal_mobiliario NUMERIC(10, 2) NOT NULL CHECK (subtotal_mobiliario >= 0),
    descuento_aplicado NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (descuento_aplicado >= 0),
    costo_entrega NUMERIC(10, 2) NOT NULL DEFAULT 250 CHECK (costo_entrega >= 0),
    total_final NUMERIC(10, 2) NOT NULL CHECK (total_final >= 0),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cotizacion_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id BIGINT NOT NULL REFERENCES cotizaciones(id) ON DELETE CASCADE,
    servicio_id BIGINT NOT NULL REFERENCES catalogo_servicios(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    importe NUMERIC(10, 2) NOT NULL CHECK (importe >= 0)
);

CREATE TABLE IF NOT EXISTS inventario_fechas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_evento DATE NOT NULL,
    servicio_id BIGINT NOT NULL REFERENCES catalogo_servicios(id) ON DELETE RESTRICT,
    cantidad_reservada INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0),
    UNIQUE (fecha_evento, servicio_id)
);

CREATE INDEX IF NOT EXISTS idx_cotizaciones_fecha_evento
    ON cotizaciones (fecha_evento);

CREATE INDEX IF NOT EXISTS idx_inventario_fechas_fecha_servicio
    ON inventario_fechas (fecha_evento, servicio_id);
